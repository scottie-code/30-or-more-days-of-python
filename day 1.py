# Find an Euclidean distance between (2, 3) and (10, 8)

# dimension 1: (2, 3)
p1 = 2
q1 = 3

# dimension 2
p2 = 10
q2 = 8

distance = ((p2 - p1) ** 2 + (q2 - q1) ** 2)**0.5

print('The Euclidean distance between (2, 3) and (10, 8) is:')
print(distance)
